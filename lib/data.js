export function getStoredData(key, fallback) {
  if (typeof window === 'undefined') return fallback;
  try {
    const data = localStorage.getItem(`clese_${key}`);
    return data ? JSON.parse(data) : fallback;
  } catch (e) {
    console.error("LocalStorage error:", e);
    return fallback;
  }
}
